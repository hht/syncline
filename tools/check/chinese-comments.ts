import ts from 'typescript';
import type { Problem, SourceText } from './problem.ts';
import { rustSource } from './rust-source.ts';

const chinese = /\p{Script=Han}/u;
// 注释只有一个链接（可带 @see），或是三斜线引用指令时，没有可写的"为什么"；工具生成文件开头的说明由工具写，改了会被覆盖（uniwind-types.d.ts）。
// Rust 的文档注释以 ///、//!、/*! 开头
const exceptions = /^(\/\/[/!]?|\/\*[*!]?)\s*((@see\s+)?<?https?:\/\/\S+\s*(\*\/)?|<reference .*|NOTE: This file is generated by \w+.*)$/;

/** 收集所有注释；注释挂在 token 的前后空白里，所以要连 token 一起遍历 */
export function comments(file: ts.SourceFile) {
  const found = new Map<number, string>();
  const text = file.getFullText();
  const visit = (node: ts.Node) => {
    const ranges = [
      ...(ts.getLeadingCommentRanges(text, node.getFullStart()) ?? []),
      ...(ts.getTrailingCommentRanges(text, node.getEnd()) ?? []),
    ];
    for (const { pos, end } of ranges) found.set(pos, text.slice(pos, end));
    for (const child of node.getChildren(file)) visit(child);
  };
  visit(file);
  return found;
}

const problem = (path: string, line: number): Problem => ({
  file: path,
  line: line + 1,
  rule: 'chinese-comment',
  message: '注释须含中文，只写为什么',
});
const exempt = (comment: string) => chinese.test(comment) || exceptions.test(comment.trim());

export function checkChineseComments(files: SourceText[]): Problem[] {
  return files.flatMap(({ path, text }) => {
    if (path.endsWith('.rs'))
      return rustSource(text).comments.flatMap(({ line, text: comment }) => (exempt(comment) ? [] : [problem(path, line)]));
    const file = ts.createSourceFile(path, text, ts.ScriptTarget.Latest, true);
    return [...comments(file)].flatMap(([pos, comment]) =>
      exempt(comment) ? [] : [problem(path, file.getLineAndCharacterOfPosition(pos).line)],
    );
  });
}
