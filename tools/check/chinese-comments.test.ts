import { expect, test } from 'vitest';
import { checkChineseComments } from './chinese-comments.ts';

const lines = (text: string) => checkChineseComments([{ path: 'a.ts', text }]).map((p) => p.line);

test('没有汉字的注释被拦下', () => {
  expect(
    lines(`// fix this later
const a = 1; /* 为什么这样：对方这里用秒 */
/**
 * returns the total
 */
function b() {}`),
  ).toEqual([1, 3]);
});

test('链接与工具指令放行', () => {
  expect(
    lines(`#!/usr/bin/env node
/// <reference types="node" />
// https://docs.powersync.com/usage/sync-rules
// @see https://www.sqlite.org/datatype3.html
/** @see https://www.sqlite.org/lang_keywords.html */
// biome-ignore lint/style/noNonNullAssertion: 中文理由
// @ts-expect-error 中文理由
// NOTE: This file is generated by uniwind and it should not be edited manually.
const a = 1;`),
  ).toEqual([]);
});

test('字符串里的双斜杠不是注释', () => {
  expect(lines(`const url = 'https://example.com'; const s = "// no";`)).toEqual([]);
});

test('忽略指令没有中文理由被拦下', () => {
  expect(
    lines(`// biome-ignore lint/style/noNonNullAssertion: because
// @ts-expect-error
const a = 1;`),
  ).toEqual([1, 2]);
});

test('JSX 里的注释也查', () => {
  expect(checkChineseComments([{ path: 'a.tsx', text: 'const a = <View>{/* todo */}</View>;' }]).map((p) => p.line)).toEqual([1]);
});

test('Rust 的注释同样要有中文：相邻的文档注释是一段，@see <链接> 放行，字符串里的 // 不算', () => {
  const rust = (text: string) => checkChineseComments([{ path: 'a.rs', text }]).map((p) => p.line);
  expect(
    rust(`//! 模块说明
//! @see <https://sqlite.org/lang.html>
/// returns the total
fn a() -> &'static str { "// no" }
// @see <https://sqlite.org/rescode.html>
/* fix this */`),
  ).toEqual([3, 6]);
});
